#!/usr/bin/env python3
"""
Re-encode audio at 48 kHz for direct TDM playback.
Uses ffmpeg directly — no third-party packages required.

Lullaby  : first 30 s of "Children Piano.mp3", 48 kHz mono, no filters,
           in CM55 .rodata.  Size: ~2.88 MB (30 s x 48 kHz x 2 bytes).

Welcome  : full duration of "welcome_sound.mp3", loudnorm normalised,
           in CM55 .rodata.  Size: ~347 KB.

Usage    : place this script and both MP3 files in the application root
           (the folder that contains proj_cm55), install FFmpeg on the PATH,
           and run:  python regen_audio_48k.py
           Output: proj_cm55/lullaby_data.c and proj_cm55/welcome_sound_data.c
           (pre-generated copies are already included in the repository).
"""

import struct, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).parent
CM55 = ROOT / "proj_cm55"   # script sits in the application root
RATE = 48000

FADE_S = 0.08   # fade-out duration (welcome sound only)

# Speaker EQ for the lullaby: compensate for small-speaker high-frequency rolloff.
# loudnorm at -10 LUFS (louder than welcome) keeps the signal hot through a
# low-efficiency driver.  The treble shelf at 3 kHz (+8 dB) pushes the music-box
# harmonics (3-8 kHz) above the speaker's natural rolloff so the "tingle"
# characteristic is audible.  TP=-1 prevents inter-sample overs.
LULLABY_AF = (
    "loudnorm=I=-10:TP=-1:LRA=7,"
    "treble=gain=8:frequency=3000:width_type=o:width=1"
)

# ─────────────────────────────────────────────────────────────────────────────
def ffmpeg_to_pcm(src: Path, trim_s: float | None, af: str | None = None) -> bytes:
    cmd = ["ffmpeg", "-y", "-i", str(src)]
    if trim_s:
        cmd += ["-t", str(trim_s)]
    cmd += ["-ac", "1", "-ar", str(RATE), "-f", "s16le", "-acodec", "pcm_s16le"]

    filters = []
    if af:
        filters.append(af)
    fade_start = (trim_s - FADE_S) if trim_s else None
    if fade_start and fade_start > 0:
        filters.append(f"afade=t=out:st={fade_start:.3f}:d={FADE_S}")
    if filters:
        cmd += ["-af", ",".join(filters)]
    cmd += ["pipe:1"]

    result = subprocess.run(cmd, capture_output=True)
    if result.returncode != 0:
        print("ffmpeg error:", result.stderr.decode(errors="replace"))
        sys.exit(1)
    return result.stdout


def write_c_array(count_sym: str, array_sym: str, pcm: bytes, path: Path,
                  ext_section: str | None = None):
    n = len(pcm) // 2
    vals = struct.unpack(f"<{n}h", pcm)
    kb = n * 2 // 1024
    loc = f"ext flash ({ext_section})" if ext_section else "CM55 .rodata"
    with open(path, "w", newline="\n") as f:
        f.write(f"/* Auto-generated by regen_audio_48k.py — {RATE} Hz mono s16le */\n")
        f.write(f'#include "{path.stem}.h"\n\n')
        f.write(f"const uint32_t {count_sym} = {n}u;\n\n")
        if ext_section:
            f.write(f'__attribute__((section("{ext_section}"), used))\n')
        f.write(f"const int16_t  {array_sym}[{n}] = {{\n")
        for i in range(0, n, 12):
            chunk = vals[i : i + 12]
            f.write("  " + ", ".join(f"{v:6d}" for v in chunk) + ",\n")
        f.write("};\n")
    print(f"  wrote {path.name}  ({n} samples, {kb} KB, {loc})")


def convert(src: Path, count_sym: str, array_sym: str, trim_s: float | None,
            out: Path, af: str | None = None, ext_section: str | None = None):
    if not src.exists():
        print(f"  WARNING: {src.name} not found -- skipping")
        return
    print(f"Converting {src.name} ...")
    pcm = ffmpeg_to_pcm(src, trim_s, af=af)
    write_c_array(count_sym, array_sym, pcm, out, ext_section=ext_section)


# ─────────────────────────────────────────────────────────────────────────────
# Lullaby: first 30 s of Children Piano.mp3, no filters, raw 48 kHz mono s16
# (full 50 s = 4.7 MB exceeds CM55 partition headroom; 30 s = 2.88 MB fits)
convert(
    src       = ROOT / "Children Piano.mp3",
    count_sym = "lullaby_pcm_samples",
    array_sym = "lullaby_pcm_data",
    trim_s    = 30.0,
    out       = CM55 / "lullaby_data.c",
    af        = None,
)

# Welcome sound: full duration, loudnorm normalised
convert(
    src       = ROOT / "welcome_sound.mp3",
    count_sym = "welcome_sound_samples",
    array_sym = "welcome_sound_pcm",
    trim_s    = None,
    out       = CM55 / "welcome_sound_data.c",
    af        = "loudnorm=I=-14:TP=-1:LRA=7",
)

print()
print("Done. Rebuild -- lullaby_data.c and welcome_sound_data.c updated.")
